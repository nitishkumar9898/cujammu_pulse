import { goToNavigation, openNavigationMenu } from './helpers/navigation';
import { expect, test } from '@playwright/test';

test('service discovery preserves permissions, keyboard focus and responsive layout', async ({ page }, testInfo) => {
  let eventsEnabled = true;
  await page.route('**/api/v1/session', route => route.fulfill({ json: { id: 1, name: 'Synthetic Student', role: 'STUDENT' } }));
  await page.route('**/api/v1/cujammu/features', route => route.fulfill({ json: { MODULE_EVENTS: eventsEnabled, MODULE_LIBRARY_TURNSTILE: true, MODULE_NOTIFICATIONS: true, MODULE_CALENDAR: true, MODULE_VOLUNTEERS: true, MODULE_READINESS: true } }));
  await page.route('**/api/v1/cujammu/recovery/library/active', route => route.fulfill({ json: [] }));
  await page.goto('/app/');
  await expect(page.getByRole('img', { name: 'Central University of Jammu seal' }).first()).toBeVisible();
  await expect(page.getByText('Central University of Jammu', { exact: true }).first()).toBeVisible();
  await page.getByRole('button', { name: 'Skip introduction' }).click();
  await openNavigationMenu(page);
  await expect(page.getByRole('tab', { name: 'Calendar', exact: true })).toBeAttached();
  await openNavigationMenu(page);
  await expect(page.getByRole('tab', { name: 'Volunteer tasks', exact: true })).toBeAttached();
  await openNavigationMenu(page);
  await expect(page.getByRole('tab', { name: 'Event readiness', exact: true })).toHaveCount(0);
  await openNavigationMenu(page);
  await expect(page.getByRole('tab', { name: 'Feature controls', exact: true })).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Open event readiness', exact: true })).toHaveCount(0);
  const search = page.getByRole('textbox', { name: 'Search campus services' });
  await search.pressSequentially('library');
  await expect(search).toBeFocused();
  await expect(page.getByRole('button', { name: 'Open smart library', exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'View departments', exact: true })).toHaveCount(0);
  await search.fill('no-such-service');
  await expect(page.getByText('No matching services', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Clear service search', exact: true }).click();
  await expect(page.getByRole('button', { name: 'View departments', exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('campus-shell-light.png'), fullPage: true });
  eventsEnabled = false;
  await page.getByRole('button', { name: 'Refresh services', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Explore events', exact: true })).toHaveCount(0);
  await openNavigationMenu(page);
  await expect(page.getByRole('tab', { name: 'Events', exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Appearance', exact: true }).click();
  await page.getByRole('radio', { name: 'Dark', exact: true }).click();
  await expect(page.getByRole('radio', { name: 'Dark', exact: true })).toHaveAttribute('aria-checked', 'true');
  await goToNavigation(page, 'Overview');
  await page.screenshot({ path: testInfo.outputPath('campus-shell-dark.png'), fullPage: true });
});
